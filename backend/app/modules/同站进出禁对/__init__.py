"""同站进出禁对（口径甲：以站距零禁对为准）。

全局唯一架构：进站站点键 == 出站站点键（站距为零）时——
- 禁止写行程账（同站 A→A 在库中不存在任何行程行）；
- 在途开腿关闭为「已旁路」，两笔刷卡命运同票落「已旁路」；
- 旁路匣钉原因=同站禁对；
- 开腿关闭与旁路证在同一事务内同成败，半截即整体回滚。

硬约束：相等站点键下的写行程/旁路是数据关系硬分叉，本模块只允许旁路一支；
禁止同票出现「旁路证 + 行程行」双落。
"""

import json

from app.seed import 此刻

NAME = "同站进出禁对"

# 全局选定架构标识。全局只贯彻「站距零禁对」一种口径。
架构 = "站距零禁对"
旁路原因 = "同站禁对"
禁对命运 = "已旁路"


def 是同站(进站站点键: str, 出站站点键: str) -> bool:
    """同站关系硬分叉判定：站点键相等即站距零。"""
    return bool(进站站点键) and 进站站点键 == 出站站点键


def 同站禁对写出站(
    conn,
    开腿,
    出站事件编号: str,
    出站站点键: str,
    处理时: str,
) -> str:
    """同站出站：关闭开腿并进旁路匣，绝不写行程账。

    全部写动作落在调用方同一事务（装载批次事务）内：任一笔失败整体回滚，
    不会出现旁路证已落而开腿/刷卡命运未翻的半截态。

    返回旁路匣载荷中钉住的旁路键（旁路-<进站>-<出站>），供裁决接口回指。
    """
    if not 是同站(开腿["进站站点键"], 出站站点键):
        raise ValueError("非站距零事件不得走同站禁对路径")

    进站事件编号 = 开腿["进站事件编号"]
    旁路键 = f"旁路-{进站事件编号}-{出站事件编号}"

    # 幂等闸门：同票已落过同站禁对旁路则原样返回，禁止双落（旁路证+行程/重复旁路）。
    for r in conn.execute(
        "SELECT 载荷 FROM 旁路匣 WHERE 原因=? AND 事件编号=?",
        (旁路原因, 出站事件编号),
    ):
        try:
            if json.loads(r["载荷"]).get("旁路键") == 旁路键:
                return 旁路键
        except (TypeError, ValueError):
            continue

    # 1) 开腿关闭进旁路（与开腿成对路径互斥：状态不再可能回「已成对」）
    conn.execute(
        "UPDATE 开腿账 SET 状态='已旁路', 更新处理时=? WHERE 开腿键=? AND 状态='在途'",
        (处理时, 开腿["开腿键"]),
    )
    # 2) 两笔刷卡命运同票：进站腿与本笔出站一起翻「已旁路」，不挂行程键
    conn.execute(
        "UPDATE 刷卡点 SET 命运=?, 行程键='' WHERE 事件编号 IN (?,?)",
        (禁对命运, 进站事件编号, 出站事件编号),
    )
    # 3) 旁路匣钉原因=同站禁对，载荷带站距零标记与开腿/旁路键
    conn.execute(
        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
        (
            旁路原因,
            开腿["卡号"],
            出站事件编号,
            json.dumps(
                {
                    "旁路键": 旁路键,
                    "开腿键": 开腿["开腿键"],
                    "进站事件编号": 进站事件编号,
                    "出站事件编号": 出站事件编号,
                    "进站站点键": 开腿["进站站点键"],
                    "出站站点键": 出站站点键,
                    "站距零": 1,
                    "架构": 架构,
                },
                ensure_ascii=False,
            ),
            处理时 or 此刻(),
        ),
    )
    return 旁路键
